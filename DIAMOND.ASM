section .text
FUN_START:
	XOR AX,AX
	MOV DS,AX
	MOV BP,SS
	MOV AX,0xA000
	MOV ES,AX
	MOV AX,0x13
	INT 0x10
	CLD
	MOV CX,0xFFFF
	MOV AX,1
	REP STOSB
	MOV CX,100
	MOV BX,3250
	PUSH BX
FUN_HT_MAIN:
	MOV BYTE [ES:BX],12
	INC BX
	LOOP FUN_HT_MAIN
	POP BX
	MOV CX,50
	PUSH BX
FUN_HT_CONT:
	ADD BX,321
	MOV BYTE [ES:BX],12
	LOOP FUN_HT_CONT
	POP BX
	MOV CX,5
@@1:;SHIFTER HI
	SUB BX,319
	MOV BYTE [ES:BX],12
	LOOP @@1
	MOV CX,90
@@2:
	INC BX
	MOV BYTE [ES:BX],12
	LOOP @@2
	MOV CX,5
@@3:
	ADD BX,321
	MOV BYTE [ES:BX],12
	LOOP @@3
	MOV CX,50
@@4:;SHIFTER LO. NOTE: This shifting functions are also
	;used as Ready Functions. Rules: BX- starting point CX- magintude of vector. 
	ADD BX,319
	MOV BYTE [ES:BX],12
	LOOP @@4
	XOR EBX,EBX
	XOR EAX,EAX
	MOV AL,12
	JMP FILL_ALGORITHM
FILFIL:
	POP AX
	MOV BYTE [ES:BX],AL
FILL_ALGORITHM:
	PUSH AX
	CMPXCHG BYTE [ES:BX],AL
	JNZ FILFIL
FUN_HALT:
	HLT
	JMP FUN_HALT
