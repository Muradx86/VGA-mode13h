ORG 0x1000
BITS 16
section .text
FUN_START:
 	XOR AX,AX
 	MOV AX,0xA000
 	MOV DS,AX
	MOV ES,AX
 	MOV AX,0x13
 	INT 0x10
 	CLD  
 	MOV CX,0xFFFF
 	MOV AX,11
 	REP STOSB
 	;TANK will be hardcoded as pixels then will be moved to back buffer.
 	MOV BX,3230 ;START POINT
 	PUSHAD
 	PUSH ES
 	XOR AX,AX
 	MOV ES,AX
 	MOV DI,0x200 ;STORE X AND Y INFO IN BUFFER - 0x200 ADDRES.
 	MOV WORD [ES:DI],10 ;Y
 	ADD DI,2 ;0x202
 	MOV WORD [ES:DI],30 ;X
 	POP ES
 	POPAD
 	MOV CX,30
@@1:
	MOV BYTE [ES:BX],12
	INC BX
	LOOP @@1
	MOV CX,3
;===============WINDOW===============
@@2:
	SUB BX,319
	MOV BYTE [ES:BX],9
	LOOP @@2
	MOV CX,15
@@3:
	MOV BYTE [ES:BX],9
	INC BX
	LOOP @@3
	MOV CX,3
@@4:
	MOV BYTE [ES:BX],9
	ADD BX,321 ;LOW
	LOOP @@4
	MOV CX,5
@@5:
	MOV BYTE [ES:BX],9
	INC BX
	LOOP @@5
	MOV CX,4
;===============WINDOW===============
@@6:
	MOV BYTE [ES:BX],12
	INC BX
	LOOP @@6
	MOV CX,4
	CALL PROC_LO_SHIFT
	MOV CX,4
	CALL PROC_LFT_SHIFT
	MOV CX,30
@@7:;BODY UNDER
	MOV BYTE [ES:BX],12
	DEC BX
	LOOP @@7
	MOV CX,5
	CALL PROC_LFT_LO_SHIFT
READY:
	CALL PUSH2BUF
	MOV DI,3250
POLL:
	HLT
	IN AL,0x60
	CMP AL,0x20
	JZ MOVE_TANK_RIGHT
	CMP AL,0x1E
	JZ MOVE_TANK_LEFT
	CMP AL,0x1F
	JZ MOVE_TANK_DOWN
	CMP AL,0x11
	JZ MOVE_TANK_UP
CONTINUE:
	JMP POLL
OS_HALT:
	HLT
	JMP OS_HALT
;================PROCEDURES================
PROC_HI_SHIFT:
	SUB BX,319
	MOV BYTE [ES:BX],12
	LOOP PROC_HI_SHIFT
	RET
PROC_LO_SHIFT:
	ADD BX,321
	MOV BYTE [ES:BX],12
	LOOP PROC_LO_SHIFT
	RET
PROC_LFT_SHIFT:
	ADD BX,319
	MOV BYTE [ES:BX],12
	LOOP PROC_LFT_SHIFT
	RET
PROC_LFT_LO_SHIFT:
	SUB BX,321
	MOV BYTE [ES:BX],12
	LOOP PROC_LFT_LO_SHIFT
	RET
PUSH2BUF:
	PUSH ES
	MOV CX,0xFFFF
	MOV AX,0xF00
	MOV ES,AX
	XOR DI,DI
	MOV SI,3230
	REP MOVSB
	POP ES
	RET
PUSH2SCR:
	PUSH DS
	MOV CX,0xFFFF
	MOV AX,0xF00
	MOV DS,AX
	XOR SI,SI
	REP MOVSB
	POP DS
	RET
CLS_SCREEN:
	XOR SI,SI
	MOV CX,0xFFFF
	MOV AX,11
	REP STOSB
	RET
;======================================
MOVE_TANK_RIGHT:
	PUSHAD
	PUSH ES
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x202
	ADD WORD [ES:DI],5
	POP ES
	POPAD
	ADD DI,5
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_LEFT:
	PUSHAD
	PUSH ES
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x202
	SUB WORD [ES:DI],5
	POP ES
	POPAD
	SUB DI,5
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_DOWN:
	PUSHAD
	PUSH ES
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	ADD WORD [ES:DI],1
	POP ES
	POPAD
	ADD DI,321
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_UP:
	PUSHAD
	PUSH ES
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	SUB WORD [ES:DI],1
	POP ES
	POPAD
	SUB DI,319
	CALL PUSH2SCR
	JMP CONTINUE
