ORG 0x1000
BITS 16
section .bss
BUF: RESB 64
section .text
FUN_START:
 	XOR AX,AX
 	MOV AX,0xA000
 	MOV DS,AX
	MOV ES,AX
 	MOV AX,0x13
 	INT 0x10
 	CLD  
 	MOV CX,0xFFFF
 	MOV AX,11
 	REP STOSB
 	;TANK will be hardcoded as pixels then will be moved to back buffer.
 	MOV BX,3230 ;START POINT
 	CALL FP80387_INIT
 	CALL PROGRAM_SOUND
 	;MOV WORD [X],30
 	;MOV WORD [Y],10
 	MOV CX,30
@@1:
	MOV BYTE [ES:BX],12
	INC BX
	LOOP @@1
	MOV CX,3
;===============WINDOW===============
@@2:
	SUB BX,319
	MOV BYTE [ES:BX],9
	LOOP @@2
	MOV CX,15
@@3:
	MOV BYTE [ES:BX],9
	INC BX
	LOOP @@3
	MOV CX,3
@@4:
	MOV BYTE [ES:BX],9
	ADD BX,321 ;LOW
	LOOP @@4
	MOV CX,5
@@5:
	MOV BYTE [ES:BX],9
	INC BX
	LOOP @@5
	MOV CX,4
;=====================================
@@6:
	MOV BYTE [ES:BX],12
	INC BX
	LOOP @@6
	MOV CX,4
	CALL PROC_LO_SHIFT
	MOV CX,4
	CALL PROC_LFT_SHIFT
	MOV CX,30
@@7:;BODY UNDER
	MOV BYTE [ES:BX],12
	DEC BX
	LOOP @@7
	MOV CX,5
	CALL PROC_LFT_LO_SHIFT
READY:
	CALL PUSH2BUF
	MOV DI,3250
POLL:
	HLT
	IN AL,0x60
	CMP AL,0x20
	JZ MOVE_TANK_RIGHT
	CMP AL,0x1E
	JZ MOVE_TANK_LEFT
	CMP AL,0x1F
	JZ MOVE_TANK_DOWN
	CMP AL,0x11
	JZ MOVE_TANK_UP
	CMP AL,0x1C
	JZ CALC_START
CONTINUE:
	JMP POLL
OS_HALT:
	HLT
	JMP OS_HALT
FP80387_INIT:
	MOV EAX,1
	SHL EAX,5
	MOV CR0,EAX
	FINIT
	RET
;================PROCEDURES================
PROC_HI_SHIFT:
	SUB BX,319
	MOV BYTE [ES:BX],12
	LOOP PROC_HI_SHIFT
	RET
PROC_LO_SHIFT:
	ADD BX,321
	MOV BYTE [ES:BX],12
	LOOP PROC_LO_SHIFT
	RET
PROC_LFT_SHIFT:
	ADD BX,319
	MOV BYTE [ES:BX],12
	LOOP PROC_LFT_SHIFT
	RET
PROC_LFT_LO_SHIFT:
	SUB BX,321
	MOV BYTE [ES:BX],12
	LOOP PROC_LFT_LO_SHIFT
	RET
PROC_PUTPX:
	PUSHAD
	PUSH ES
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	MOV WORD BX,[ES:DI]
	ADD DI,4
	MOV WORD AX,[ES:DI]
	IMUL BX,320
	ADD BX,AX
	MOV BYTE [ES:BX],6
	POPAD
	RET
PUSH2BUF:
	PUSH ES
	MOV CX,0xFFFF
	MOV AX,0xF00
	MOV ES,AX
	XOR DI,DI
	MOV SI,3230
	REP MOVSB
	POP ES
	RET
PUSH2SCR:
	PUSH DS
	MOV CX,0xFFFF
	MOV AX,0xF00
	MOV DS,AX
	XOR SI,SI
	REP MOVSB
	POP DS
	RET
CLS_SCREEN:
	XOR SI,SI
	MOV CX,0xFFFF
	MOV AX,11
	REP STOSB
	RET
PROC_REFINE:
	PUSHAD
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	MOV DWORD EBX,[ES:DI]
	ADD DI,4
	MOV DWORD EAX,[ES:DI]
	ADD EAX,30
	ADD EBX,10
	MOV DWORD [ES:DI],EAX
	SUB DI,4
	MOV DWORD [ES:DI],EBX
	POPAD
	RET
PROC_PUTP:
	PUSHAD
	MOV WORD BX,[ES:DI]
	ADD DI,4
	MOV WORD AX,[ES:DI]
	IMUL BX,320
	ADD BX,AX
	MOV BYTE [ES:BX],6
	POPAD
	RET
PROC_MKBUF_XY:
	PUSH DI
	PUSH ES
	PUSH EAX
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	MOV DWORD EAX,[EBP+20]
	MOV DWORD EBX,[EBP+24]
	MOV DWORD [ES:DI],EAX ;Y
	ADD DI,4
	MOV DWORD [ES:DI],EBX ;X
	POP EAX
	POP ES
	POP DI
	RET
PROC_REFRESH_MIX:
	PUSH EBP
	MOV EBP,ESP
	;SAFE
	PUSH EDI
	PUSH EAX
	MOVZX EDI,DI
	MOV DWORD [EBP+16],EDI
	MOV AX,320
	DIV DI
	MOVZX EAX,AX
	MOV DWORD [EBP+24],EAX ;Y COORDINATE
	IMUL EAX,10
	SUB EDI,EAX ;X COORDINATE
	MOV DWORD [EBP+20],EDI
	CALL PROC_MKBUF_XY	
	POP EAX
	POP EDI
	POP EBP
	;SAFE
	RET
;======================================
MOVE_TANK_RIGHT:
	PUSH EBP
	MOV EBP,ESP
	ADD DI,2	
	CALL PROC_REFRESH_MIX
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_LEFT:
	PUSH EBP
	MOV EBP,ESP
	CALL PROC_REFRESH_MIX
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_DOWN:
	PUSH EBP
	MOV EBP,ESP	
	ADD DI,321
	CALL PROC_REFRESH_MIX
	CALL PUSH2SCR
	JMP CONTINUE
MOVE_TANK_UP:
	PUSH EBP
	MOV EBP,ESP
	SUB DI,319
	CALL PUSH2SCR
	JMP CONTINUE
;==========SOUND============
PROGRAM_SOUND:
	PUSH DX
	MOV DX,0x43
	MOV AL,0xB6
	OUT DX,AL
	MOV DX,0x61
	IN AL,DX
	OR AL,3
	OUT DX,AL
	MOV DWORD EBX,[SOUND_FREQUENCY]
	PUSH EBX
	AND EBX,0xFF
	MOV AL,BL
	OUT 0x42,AL
	POP EBX
	SHR EBX,0x8
	MOV AL,BL
	OUT DX,AL
	POP DX
	RET
;===========================
;=======COORDINATERS========
CALC_START:
CALC_X_NEXT:
	PUSH EBP
	MOV EBP,ESP
	FILD DWORD [CONST_HEIGHT]
	FMUL DWORD [TEMP1] ;2H
	FDIV DWORD [CONST_G]
	FDIV DWORD [TEMP2] ;2H/G
	FSQRT
	FMUL DWORD [CONST_VELOCITY]
	FRNDINT
	;SAFE
	PUSH ES
	PUSH DI
	PUSH AX
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x204
	FISTP DWORD [ES:DI] ;ST(0) CLEARED
	POP AX
	POP DI
	POP ES
	;SAFE
CALC_Y_NEXT:
	FILD DWORD [CONST_VELOCITY]
	FMUL DWORD [CONST_TIME] ;V0 * T
	FISTP DWORD [EBP+8] ;V0 * T ADDRES
	FILD DWORD [CONST_TIME]
	FMUL DWORD [CONST_TIME] ;T^2
	FMUL DWORD [CONST_G]
	FDIV DWORD [TEMP3] ;GT^2. G IS 98 SO -> 98*T^2/20
	FRNDINT
	FISTP DWORD [EBP+16]
	MOV DWORD ECX,[EBP+8] ;V0*T
	MOV DWORD EAX,[EBP+16] ;GT^2/2
	SUB ECX,EAX
	;SAFE
	PUSH ES
	PUSH DI
	PUSH AX
	XOR AX,AX
	MOV ES,AX
	MOV DI,0x200
	MOV DWORD [ES:DI],ECX
	FISTP DWORD [ES:DI] ;ST(0) CLEARED
	POP AX
	POP DI
	POP ES
	;****************MOV DWORD [Y],EAX
	POP EBP
DRAW_TO_NEXT:
	CALL PROC_REFINE
	CALL PROC_PUTP
	JMP CONTINUE
;============================
TEMP1 DD 2
TEMP2 DD 10
TEMP3 DD 20
THETA1 DW 60
THETA2 DW 15

CONST_G DD 98 ;DIV
CONST_HEIGHT DD 10
CONST_VELOCITY DD 10
CONST_TIME DD 5

BALL_HIGH DB 6,6,6,6
BALL_MID DB 6,6,6,6,6
BALL_LOW DB 11,6,6,6,6,11

SOUND_FREQUENCY DD 59659 ;div 20
;0x200 -> Y ;0x204 -> X
