BITS 16
ORG 0x7C00
section .bss
BT_DRIVE: RESB 8
;TempleOS Boot Loader.
section .text
BT_START:
	CLI
	CLD
	XOR EAX,EAX
	MOV DS,AX
	MOV ES,AX
	MOV SS,AX
	MOV SP,0x9000
	STI
	MOV BYTE [BT_DRIVE],DL
	IN AL,0x92
	OR AL,2
	OUT 0x92,AL
	MOV DH,0
	MOV CH,0
	MOV CL,2
	MOV AL,60
	MOV BX,0x1000
	MOV BYTE DL,[BT_DRIVE]

	MOV AH,2
	INT 0x13

	JMP 0x1000
times 446-($-$$) db 0
DW 0x80
DB 0
DB 0
DB 0
DB 0
DB 0 ;HEAD
DB 60 ;SECTOR
DB 0 ;CYLINDER
DD 0x1000
DD 60
times 510-($-$$) db 0
dw 0xaa55
