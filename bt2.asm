ORG 0x1000
BITS 16
section .bss
FUN_BUFFER: RESB 40
FUN_BUFFER_BACK: RESB 40
FUN_SNAKE_BODY: RESB 30
section .text
FUN_START:
	XOR AX,AX
	MOV DS,AX
	MOV AX,0xA000
	MOV ES,AX
	MOV AX,0x13
	INT 0x10
	CLD
	MOV CX,0xFFFF
	MOV AX,11
	REP STOSB
	LEA BX,FUN_BUFFER
	LEA SI,FUN_SNAKE_BODY
	MOV DX,0
FUN_RECOVER:
	MOV BYTE [BX],8
	MOV BYTE [SI],12
	INC BX
	INC DX
	INC SI
	CMP DX,40
	JNZ FUN_RECOVER
	JMP FUN_GRAPHICS
FUN_SNAKE_GR:
	CLD
	LEA SI,FUN_SNAKE_BODY
	MOV CX,10
	REP MOVSB
	RET
FUN_ALGORITHM:
	CLD
	LEA SI,FUN_BUFFER
	MOV CX,40
	REP MOVSB
	SUB DI,1
	PUSH DI
FUN_BACKBUFFER:
	PUSH DI
	LEA SI,FUN_BUFFER_BACK
	MOV CX,40
	MOV AX,9
	STD
	REP STOSB
	POP DI
	RET
FUN_GRAPHICS:
	MOV DI,0    ;X
	MOV CX,0	;Y
FUN_DRAW_SNAKE:
	CALL FUN_SNAKE_GR
	INC DI
POLL:
	IN AL,0x60
	CMP AL,0x20
	JNZ POLL
	CALL FUN_SNAKE_GR		;init
	CALL FUN_BACKBUFFER
	CALL FUN_SNAKE_GR
	JMP POLL
FUN_HALT:
	HLT
	JMP FUN_HALT
